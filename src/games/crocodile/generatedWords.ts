export const generatedCrocodileWords: CrocodileWord[] = phraseSeeds.flatMap((seed) => buildSeedWords(seed));

function buildSeedWords(seed: PhraseSeed) {
  const words: CrocodileWord[] = [];

  seed.nouns.forEach((noun, index) => {
    words.push({
      id: `${seed.prefix}_noun_${index + 1}`,
      text: capitalize(noun),
      category: seed.category,
      difficulty: index < 5 ? "easy" : "medium",
      isPhrase: false
    });
  });

  seed.adjectives.forEach((adjective, index) => {
    words.push(makeWord(seed, `adj_${index + 1}`, `${adjective} ${seed.nouns[index % seed.nouns.length]}`, index < 4 ? "medium" : "hard"));
  });

  seed.actions.forEach((action, index) => {
    words.push(
      makeWord(
        seed,
        `act_${index + 1}`,
        `${action} ${seed.nouns[(index + 2) % seed.nouns.length]} ${seed.places[index % seed.places.length]}`,
        index < 5 ? "medium" : "hard"
      )
    );
  });

  seed.places.slice(0, 6).forEach((place, index) => {
    words.push(
      makeWord(
        seed,
        `place_${index + 1}`,
        `${seed.nouns[(index + 4) % seed.nouns.length]} ${place}`,
        index < 3 ? "easy" : "medium"
      )
    );
  });

  return words;
}

function makeWord(seed: PhraseSeed, suffix: string, text: string, difficulty: CrocodileDifficulty): CrocodileWord {
  return {
    id: `${seed.prefix}_${suffix}`,
    text: capitalize(text),
    category: seed.category,
    difficulty,
    isPhrase: true
  };
}

function capitalize(value: string) {
  return value.slice(0, 1).toLocaleUpperCase("ru-RU") + value.slice(1);
}
