export const generatedCrocodileWords: CrocodileWord[] = wordPacks.flatMap((pack) => [
  ...pack.singles.map((item, index) => makeWord(pack, `single_${index + 1}`, item, false)),
  ...pack.phrases.map((item, index) => makeWord(pack, `phrase_${index + 1}`, item, true))
]);

function makeWord(pack: WordPack, suffix: string, item: WordItem, isPhrase: boolean): CrocodileWord {
  const [text, difficulty]: [string, CrocodileDifficulty] = Array.isArray(item) ? item : [item, isPhrase ? "medium" : "easy"];

  return {
    id: `${pack.prefix}_${suffix}`,
    text,
    category: pack.category,
    difficulty,
    isPhrase
  };
}
